def sic_to_naics6(sic_raw: object) -> Optional[str]:
  """Resolve a SIC code (any int / string form) to a canonical NAICS-6.

  Returns None if SIC is empty/invalid. Falls through to a NAICS-2-padded
  string (NAICS-2 + '0000') when the SIC isn't in the SIC_TO_NAICS_6 table
  but its 2-digit prefix is a known SIC division. The padded form keeps
  NAICS-6 length consistency for downstream callers.
  """
  if sic_raw is None:
    return None
  sic_clean = "".join(ch for ch in str(sic_raw) if ch.isdigit())
  if not sic_clean:
    return None
  sic_padded = sic_clean.zfill(4)[:4]
  exact = SIC_TO_NAICS_6.get(sic_padded)
  if exact:
    return exact
  sic2 = sic_padded[:2]
  naics2 = _SIC_2_TO_NAICS_2.get(sic2)
  if naics2:
    return naics2.ljust(6, "0")
  return None
